const AnimatedSignature = () => {
  const svgRef = useRef(null);
  const containerRef = useRef(null);

  const playAnimation = () => {
    if (!svgRef.current) return;
    const paths = svgRef.current.querySelectorAll('.signature-glyph');

    // 1. Reset each path with total length
    paths.forEach((path) => {
      const length = path.getTotalLength();
      path.style.strokeDasharray = `${length}`;
      path.style.strokeDashoffset = `${length}`;
      path.style.fillOpacity = '0';
    });

    const tl = gsap.timeline();

    // 2. Animate stroke sequentially (pen writing out letters)
    tl.to(paths, {
      strokeDashoffset: 0,
      duration: 1.4,
      stagger: 0.1,
      ease: 'power2.inOut',
    })
    // 3. Smoothly fade in luminous fill
    .to(paths, {
      fillOpacity: 0.95,
      duration: 0.6,
      stagger: 0.05,
      ease: 'power1.out',
    }, '-=0.4');
  };

  useEffect(() => {
    if (!svgRef.current || !containerRef.current) return;

    const paths = svgRef.current.querySelectorAll('.signature-glyph');
    paths.forEach((path) => {
      const length = path.getTotalLength();
      path.style.strokeDasharray = `${length}`;
      path.style.strokeDashoffset = `${length}`;
      path.style.fillOpacity = '0';
    });

    const trigger = ScrollTrigger.create({
      trigger: containerRef.current,
      start: 'top 85%',
      onEnter: () => playAnimation(),
      once: false,
    });

    return () => trigger.kill();
  }, []);

  return (
    <div
      ref={containerRef}
      className="w-full flex flex-col items-center justify-center py-10 md:py-16 relative overflow-hidden group cursor-pointer"
      onClick={playAnimation}
      title="Click to replay calligraphy signature"
    >
      {/* Decorative ambient background glow */}
      <div className="absolute top-1/2 left-1/2 -translate-x-1/2 -translate-y-1/2 w-3/4 max-w-2xl h-36 bg-cyan-500/10 rounded-full blur-3xl pointer-events-none group-hover:bg-cyan-500/20 transition-all duration-700" />

      <div className="flex items-center gap-2 mb-3 z-10">
        <span className="font-tech text-xs uppercase tracking-[0.25em] text-cyan-400/80">
          ✦ Calligraphy Signature
        </span>
        <span className="font-calligraphy text-base text-yellow-300/80 hidden sm:inline-block">
          (click to replay)
        </span>
      </div>

      {/* SVG Signature of "Saqlain" with authentic Calligraphy Glyphs */}
      <div className="w-full max-w-2xl px-4 flex justify-center z-10">
        <svg
          ref={svgRef}
          id="Visual"
          xmlns="http://www.w3.org/2000/svg"
          viewBox="30 65 590 190"
          className="w-full h-auto max-h-48 md:max-h-60 object-contain filter drop-shadow-[0_0_18px_rgba(34,211,238,0.45)]"
        >
          <defs>
            <linearGradient id="signature-grad" x1="0%" y1="0%" x2="100%" y2="0%">
              <stop offset="0%" stopColor="#22d3ee" />
              <stop offset="35%" stopColor="#38bdf8" />
              <stop offset="70%" stopColor="#19f7ad" />
              <stop offset="100%" stopColor="#c084fc" />
            </linearGradient>
            <filter id="sig-glow" x="-20%" y="-20%" width="140%" height="140%">
              <feGaussianBlur stdDeviation="2.5" result="blur" />
              <feMerge>
                <feMergeNode in="blur" />
                <feMergeNode in="SourceGraphic" />
              </feMerge>
            </filter>
          </defs>

          <g
            stroke="url(#signature-grad)"
            strokeWidth="2.5"
            strokeLinecap="round"
            strokeLinejoin="round"
            filter="url(#sig-glow)"
          >
            {glyphPaths.map((glyph) => (
              <path
                key={glyph.id}
                id={`glyph-${glyph.id}`}
                className="signature-glyph"
                d={glyph.d}
                fill="url(#signature-grad)"
                style={{ fillOpacity: 0 }}
              />
            ))}
          </g>
        </svg>
      </div>
    </div>
  );
};

export default AnimatedSignature;
